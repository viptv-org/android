import assert from 'node:assert/strict';
import { boundedCategoryCount, categoryFixturePage } from './category-fixture.mjs';
const url = cursor => new URL(`https://fixture.invalid/api/v2/iptv/live/categories?limit=200${cursor ? '&cursor=' + cursor : ''}`);
assert.equal(boundedCategoryCount('invalid'), 0);
assert.equal(boundedCategoryCount(-1), 0);
assert.equal(boundedCategoryCount(100001), 1000);
assert.equal(boundedCategoryCount(400.9), 400);
assert.deepEqual(categoryFixturePage(url(), 0).body.items, [{ id: 'news', name: 'News' }]);
const first = categoryFixturePage(url(), 400).body;
assert.equal(first.items.length, 200); assert.equal(first.items[0].id, 'category-0');
assert.equal(first.previous_cursor, null); assert(first.next_cursor);
const second = categoryFixturePage(url(first.next_cursor), 400).body;
assert.equal(second.items.length, 200); assert.equal(second.items[0].id, 'category-200');
assert.equal(second.next_cursor, null); assert(second.previous_cursor);
assert.deepEqual(categoryFixturePage(url(second.previous_cursor), 400).body.items, first.items);
assert.equal(categoryFixturePage(url(first.next_cursor), 401).status, 400);
assert.equal(categoryFixturePage(url('not-a-cursor'), 400).status, 400);
assert.equal(categoryFixturePage(new URL('https://fixture.invalid/?limit=201'), 400).status, 400);
console.log('Bounded/default category fixture, 400 forward/reverse, cursor binding and malformed refusals: PASS');
